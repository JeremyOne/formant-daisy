float width (const juce::String& text, float scale)
{
    const int n = text.length();
    return n <= 0 ? 0.0f : (float) (n * 6 - 1) * scale;
}

void draw (juce::Graphics& g, const juce::String& text, float x, float y, float scale, juce::Colour colour)
{
    g.setColour (colour);
    const auto& map = glyphs();
    float cx = x;
    for (auto ch : text)
    {
        auto c = juce::CharacterFunctions::toUpperCase (ch);
        auto it = map.find (c);
        if (it != map.end())
        {
            for (int row = 0; row < 7; ++row)
            {
                const char* bits = it->second[(size_t) row];
                for (int col = 0; col < 5; ++col)
                    if (bits[col] == '#')
                        g.fillRect (cx + (float) col * scale, y + (float) row * scale, scale, scale);
            }
        }
        cx += 6.0f * scale;
    }
}

void drawCentred (juce::Graphics& g, const juce::String& text, juce::Rectangle<float> area, float scale, juce::Colour colour)
{
    const float w = width (text, scale);
    draw (g, text, area.getCentreX() - w * 0.5f, area.getCentreY() - height (scale) * 0.5f, scale, colour);
}
