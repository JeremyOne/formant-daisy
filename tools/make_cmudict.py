#!/usr/bin/env python3
"""Pack the CMU Pronouncing Dictionary into Source/engine/CmuDict.cpp.

Usage: python3 tools/make_cmudict.py path/to/cmudict.dict

Get cmudict.dict from https://github.com/cmusphinx/cmudict (BSD-style
license, see third_party/cmudict/LICENSE).

Format of the packed bytes (words sorted, front-coded):
    per entry: [shared prefix length] [suffix length] [suffix letters]
               [phoneme count] [phoneme codes]
Phoneme codes index PHONES below. Unstressed AH (AH0) becomes "ax", and unstressed ER before a vowel becomes "ax r".
Only the first pronunciation of each word is kept, and only words made
of a-z and apostrophes.
"""
import re
import sys

PHONES = [
    "iy", "ih", "eh", "ae", "aa", "ao", "ah", "uh", "uw", "er", "ax", "ey", "ay", "oy", "aw", "ow",
    "p", "b", "t", "d", "k", "g", "f", "v", "th", "dh", "s", "z", "sh", "zh", "ch", "jh", "hh",
    "m", "n", "ng", "l", "r", "w", "y",
]
CODE = {p: i for i, p in enumerate(PHONES)}


VOWELS = {"AA", "AE", "AH", "AO", "AW", "AY", "EH", "ER", "EY", "IH", "IY", "OW", "OY", "UH", "UW"}


def convert(arpa):
    out = []
    for i, tok in enumerate(arpa):
        base = re.sub(r"\d", "", tok).lower()
        if base == "ah" and tok.endswith("0"):
            base = "ax"
        # unstressed ER before a vowel is a light "uh-r" (inspiration, wandering)
        if tok == "ER0" and i + 1 < len(arpa) and re.sub(r"\d", "", arpa[i + 1]) in VOWELS:
            out += [CODE["ax"], CODE["r"]]
            continue
        if base not in CODE:
            return None
        out.append(CODE[base])
    return out


def main():
    src = sys.argv[1]
    entries = {}
    with open(src, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            word = parts[0]
            if "(" in word:  # alternate pronunciation
                continue
            if not re.fullmatch(r"[a-z']+", word) or len(word) > 255:
                continue
            ph = convert(parts[1:])
            if not ph or len(ph) > 255:
                continue
            entries[word] = ph

    data = bytearray()
    prev = ""
    for word in sorted(entries):
        shared = 0
        while shared < min(len(prev), len(word), 255) and prev[shared] == word[shared]:
            shared += 1
        suffix = word[shared:].encode("ascii")
        ph = entries[word]
        data += bytes([shared, len(suffix)]) + suffix + bytes([len(ph)]) + bytes(ph)
        prev = word

    lines = [
        "// Generated by tools/make_cmudict.py from the CMU Pronouncing Dictionary.",
        "// Copyright (C) 1993-2015 Carnegie Mellon University. All rights reserved.",
        "// BSD-style license: see third_party/cmudict/LICENSE. Do not edit by hand.",
        '#include "CmuDict.h"',
        "",
        "namespace fd",
        "{",
        "const char* const kCmuPhones[] = { " + ", ".join(f'"{p}"' for p in PHONES) + " };",
        f"const int kCmuPhoneCount = {len(PHONES)};",
        f"const unsigned int kCmuWordCount = {len(entries)};",
        f"const unsigned int kCmuDataSize = {len(data)};",
        "const unsigned char kCmuData[] = {",
    ]
    for i in range(0, len(data), 40):
        lines.append(",".join(str(b) for b in data[i:i + 40]) + ",")
    lines += ["};", "} // namespace fd", ""]
    with open("Source/engine/CmuDict.cpp", "w", encoding="ascii") as f:
        f.write("\n".join(lines))
    print(f"{len(entries)} words, {len(data)} bytes")


if __name__ == "__main__":
    main()
