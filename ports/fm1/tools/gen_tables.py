#!/usr/bin/env python3
"""Generate daisy_fx_tables.h for the FM-1 port from the plugin's phoneme table.

Usage: python3 ports/fm1/tools/gen_tables.py Source/engine/Phonemes.cpp > ports/fm1/src/daisy_fx_tables.h

Everything the integer engine needs is precomputed here, so the device never
touches floating point:
  - the phonemes (formant targets, bandwidths, amplitudes, timing), with codes
    1..40 in the same order as the CMU dictionary packer (0 = silence)
  - the frication noise shapes
  - DFX_COS_Q30: cos(pi * k / 1024), k = 0..1024 (for 2 cos(2 pi F / FS))
  - DFX_BWR_Q30: exp(-pi * B / FS) for B = 0, 8, 16, ... Hz (the pole radius)
  - DFX_NOTE_INC: the phase increment of each MIDI note (Q32 per sample)
"""
import math
import re
import sys

FS = 44100
PHONES = [
    "iy", "ih", "eh", "ae", "aa", "ao", "ah", "uh", "uw", "er", "ax", "ey", "ay", "oy", "aw", "ow",
    "p", "b", "t", "d", "k", "g", "f", "v", "th", "dh", "s", "z", "sh", "zh", "ch", "jh", "hh",
    "m", "n", "ng", "l", "r", "w", "y",
]
KINDS = ["Silence", "Vowel", "Diphthong", "StopVoiceless", "StopVoiced", "FricVoiceless", "FricVoiced",
         "AffricateVoiceless", "AffricateVoiced", "Nasal", "Liquid", "Glide", "Aspirate"]
FRICS = ["FR_NONE", "FR_S", "FR_SH", "FR_F", "FR_TH", "FR_BURST_P", "FR_BURST_T", "FR_BURST_K"]


def num(s):
    return float(s.rstrip("f"))


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    rows = {}
    for m in re.finditer(r'\{\s*"([a-z_]+)",\s*"[^"]*",\s*Kind::(\w+),([^}]*)\}', src):
        name, kind, rest = m.group(1), m.group(2), m.group(3)
        f = [x.strip() for x in rest.split(",")]
        off = f[12].strip('"') if f[12] != "nullptr" else None
        rows[name] = dict(kind=KINDS.index(kind), F=[num(f[0]), num(f[1]), num(f[2])], B=[num(f[3]), num(f[4]), num(f[5])],
                          av=num(f[6]), af=num(f[7]), ah=num(f[8]), dur=num(f[9]), fric=FRICS.index(f[10]),
                          fnz=num(f[11]), off=off)
    fric = []
    for m in re.finditer(r'/\*\s*(\w+)\s*\*/\s*\{([^}]*)\}', src):
        v = [num(x.strip()) for x in m.group(2).split(",")]
        fric.append((m.group(1), v))
    order = ["_"] + PHONES
    missing = [p for p in order if p not in rows]
    if missing:
        sys.exit(f"missing phonemes: {missing}")

    q15 = lambda x: int(round(x * 32767))
    out = []
    w = out.append
    w("/* Generated by ports/fm1/tools/gen_tables.py from Source/engine/Phonemes.cpp. Do not edit. */")
    w("#ifndef DAISY_FX_TABLES_H")
    w("#define DAISY_FX_TABLES_H")
    w("#include <stdint.h>")
    w(f"#define DFX_TABLE_FS {FS}")
    w(f"#define DFX_NPHONE {len(order)}")
    w("enum { " + ", ".join(f"DFX_K_{k.upper()}" for k in KINDS) + " };")
    w("typedef struct {")
    w("    char name[3];")
    w("    uint8_t kind, fric, off;        /* off: diphthong offglide code, 0 = none */")
    w("    uint16_t F[3], B[3], fnz;       /* Hz (fnz 0 = no nasal zero) */")
    w("    int16_t av, af, ah;             /* Q15 */")
    w("    uint16_t dur;                   /* ms */")
    w("} dfx_phone_t;")
    w("static const dfx_phone_t DFX_PHONES[DFX_NPHONE] = {")
    for i, n in enumerate(order):
        r = rows[n]
        off = order.index(r["off"]) if r["off"] else 0
        w(f'    {{"{n}", {r["kind"]}, {r["fric"]}, {off}, {{{int(r["F"][0])}, {int(r["F"][1])}, {int(r["F"][2])}}}, '
          f'{{{int(r["B"][0])}, {int(r["B"][1])}, {int(r["B"][2])}}}, {int(r["fnz"])}, {q15(r["av"])}, {q15(r["af"])}, '
          f'{q15(r["ah"])}, {int(r["dur"])}}}, /* {i} */')
    w("};")
    w("typedef struct { uint16_t f1, b1, f2, b2; int16_t a1, a2, byp; } dfx_fric_t; /* Hz, Q15 */")
    w("static const dfx_fric_t DFX_FRIC[] = {")
    for name, v in fric:
        w(f"    {{{int(v[0])}, {int(v[1])}, {int(v[3])}, {int(v[4])}, {q15(v[2])}, {q15(v[5])}, {q15(v[6])}}}, /* {name} */")
    w("};")
    w("/* cos(pi k / 1024), Q30 */")
    w("static const int32_t DFX_COS_Q30[1025] = {")
    vals = [int(round(math.cos(math.pi * k / 1024) * (1 << 30))) for k in range(1025)]
    for i in range(0, 1025, 8):
        w("    " + ", ".join(str(x) for x in vals[i:i + 8]) + ",")
    w("};")
    w("/* exp(-pi B / FS) for B = 8 k Hz, k = 0..511, Q30 */")
    w("static const int32_t DFX_BWR_Q30[512] = {")
    vals = [int(round(math.exp(-math.pi * 8 * k / FS) * (1 << 30))) for k in range(512)]
    for i in range(0, 512, 8):
        w("    " + ", ".join(str(x) for x in vals[i:i + 8]) + ",")
    w("};")
    w("/* phase increment per sample of MIDI note n (Q32) */")
    w("static const uint32_t DFX_NOTE_INC[128] = {")
    vals = [min(0xFFFFFFFF, int(round(440 * 2 ** ((n - 69) / 12) / FS * 2 ** 32))) for n in range(128)]
    for i in range(0, 128, 8):
        w("    " + ", ".join(f"{x}u" for x in vals[i:i + 8]) + ",")
    w("};")
    w("/* exp(-dt / tau) for the control tick (16 samples) and tau = 1..255 ms, Q15 (smoothing) */")
    w("static const int16_t DFX_TAU_Q15[256] = {")
    dt = 16 / FS * 1000
    vals = [0] + [int(round(math.exp(-dt / t) * 32767)) for t in range(1, 256)]
    for i in range(0, 256, 8):
        w("    " + ", ".join(str(x) for x in vals[i:i + 8]) + ",")
    w("};")
    w("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
